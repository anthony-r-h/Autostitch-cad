// Generate native-fit fixtures from the independent selector and catalog.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {selectFit} from './fit-oracle.mjs';
const catalog = JSON.parse(fs.readFileSync(new URL('./cases.json', import.meta.url), 'utf8'));
const matrix = catalog.oracle.native;
const lispPath = relative => JSON.stringify(fileURLToPath(new URL(relative, import.meta.url)).replaceAll('\\', '/'));

const cases = [];
for (const p of catalog.oracle.pitches) {
  for (const D of matrix.lengths) {
    for (const [start, end] of matrix.protections) {
      cases.push({p, D, start, end});
    }
  }
  for (const radius of matrix.radii) {
    const R = radius === 'p/2' ? p / 2 : radius === 'p/2+0.01' ? p / 2 + 0.01 : radius;
    for (const sweep of matrix.sweeps) {
      for (const [start, end] of matrix.arcProtections) cases.push({p, R, sweep, start, end});
    }
  }
}
const lisp = value => value === null ? 'nil' : Array.isArray(value)
  ? '(' + value.map(lisp).join(' ') + ')' : String(value);
const fixtures = cases.map(spec => {
  const expected = selectFit(spec);
  return [spec.R ? 'arc' : 'line', spec.R ? spec.sweep : spec.D, spec.p, spec.R ?? 0,
    spec.start, spec.end, expected?.n ?? null, expected?.k ?? null,
    expected?.i ?? null, expected?.correctedPitch ?? null];
});
const content = `;;; Generated by tests/build-native-oracle.mjs. Pure geometry; no DWG mutation.
(load ${lispPath('../source/autostitch-geometry.lsp')})
(defun ast:oracle-check (fixture / result expected-count expected-k actual-count actual-k good gaps total)
  (setq result (if (= (car fixture) 'line)
    (ast:g-fit-line (nth 1 fixture) (nth 2 fixture) (nth 4 fixture) (nth 5 fixture) T)
    (ast:g-fit-arc (nth 3 fixture) (nth 1 fixture) (nth 2 fixture) (nth 4 fixture) (nth 5 fixture) T)))
  (setq expected-count (nth 6 fixture) expected-k (nth 7 fixture)
        actual-count (cdr (assoc 'count result)) actual-k (cdr (assoc 'changed result)))
  (setq good (if expected-count
    (and (cdr (assoc 'ok result)) (= actual-count expected-count) (= actual-k expected-k)
         (or (= expected-k 0) (= (cdr (assoc 'block-start result)) (nth 8 fixture))))
    (not (cdr (assoc 'ok result)))))
  (if (and good expected-count (> expected-k 0))
    (setq good (equal (nth (nth 8 fixture) (cdr (assoc 'gaps result))) (nth 9 fixture) 1e-8)))
  (if good (setq ast:oracle-passed (1+ ast:oracle-passed))
    (setq ast:oracle-failures (cons (list fixture result) ast:oracle-failures))))
(setq ast:oracle-passed 0 ast:oracle-failures nil)
(foreach ast:oracle-fixture '${lisp(fixtures)}
  (setq ast:oracle-result (vl-catch-all-apply 'ast:oracle-check (list ast:oracle-fixture)))
  (if (vl-catch-all-error-p ast:oracle-result)
    (setq ast:oracle-failures (cons (list ast:oracle-fixture (vl-catch-all-error-message ast:oracle-result)) ast:oracle-failures))))
(setq ast:oracle-file (open ${lispPath('../output/native/geometry-oracle.txt')} "w"))
(write-line (strcat "PASSED=" (itoa ast:oracle-passed) " FAILED=" (itoa (length ast:oracle-failures))) ast:oracle-file)
(foreach ast:oracle-failure ast:oracle-failures (write-line (vl-prin1-to-string ast:oracle-failure) ast:oracle-file))
(close ast:oracle-file)
(princ)
`;
fs.mkdirSync(new URL('../output/native/', import.meta.url), {recursive: true});
const destination = new URL('../output/native/geometry-oracle.lsp', import.meta.url);
fs.writeFileSync(destination, content);
console.log(`Generated ${fixtures.length} independent native fit fixtures.`);
